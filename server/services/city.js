/**
 * 「地址」→「城市」归一化（2026-10-12，使用者要求）
 *
 * 背景
 *   源表那一列叫「地址」。早期大家只填城市名（`南宁市` / `玉林市`），
 *   后来逐渐填成**完整地址**（`广西南宁市青秀区古城路39号` /
 *   `山东省威海市环翠区文化西路197号`）—— 实测 55 个不同值里大半带街道门牌。
 *   而看板那一列叫「城市」：塞整条地址会**换行撑高每一行**（一屏只能看 5 条），
 *   也不便于按城市看。使用者要求：**只到市**。
 *
 * 为什么放在**入库时**、而不是只在界面上截
 *   这一列有 4 个下游：
 *     ① 明细列表          ② 明细页「城市」筛选下拉（`SELECT DISTINCT city`）
 *     ③ 待处理优先级清单   ④ 明细 Excel 导出
 *   只在界面截 ⇒ 下拉里还是整条地址，而筛选是 `WHERE city = $n` **精确匹配**
 *   ⇒ 选了城市一条都筛不出来（典型的「看着能用其实失效」）。
 *   入库归一化 ⇒ 4 处自动一致，筛选照常命中。
 *
 * 解析顺序（已拿当前 55 个真实取值逐条核对）
 *   ① 剥掉省级前缀后取到**第一个「市」**        `广西南宁市青秀区古城路39号` → `南宁市`
 *   ② 没有「市」就找**已知城市名**               `…自由贸易试验区南宁片区云英路15号…` → `南宁市`
 *   ③ 没有「市」但有「县」→ 取到第一个「县」     `宁明县城中镇明阳街3号` → `宁明县`
 *   ④ 兜底 → **原样返回**（绝不静默丢信息）
 *
 * ⚠️ 不做的事：`城港市`（源表把「防城港市」写错了，25 条）**保持原样** ——
 *    使用者的口径是「应改源表不该改库」，已明确不处理。
 */

/** 省级全称（含直辖市 / 自治区 / 特别行政区） */
const PROV_FULL =
  /^(?:北京市|天津市|上海市|重庆市|河北省|山西省|辽宁省|吉林省|黑龙江省|江苏省|浙江省|安徽省|福建省|江西省|山东省|河南省|湖北省|湖南省|广东省|海南省|四川省|贵州省|云南省|陕西省|甘肃省|青海省|台湾省|内蒙古自治区|广西壮族自治区|西藏自治区|宁夏回族自治区|新疆维吾尔自治区|香港特别行政区|澳门特别行政区)/

/** 省级简称（源表里出现过「广西南宁市」「四川德阳市」「广西区防城港市」这种写法） */
const PROV_ABBR =
  /^(?:内蒙古|广西|西藏|宁夏|新疆|香港|澳门|北京|天津|上海|重庆|河北|山西|辽宁|吉林|黑龙江|江苏|浙江|安徽|福建|江西|山东|河南|湖北|湖南|广东|海南|四川|贵州|云南|陕西|甘肃|青海|台湾)/

/** 从「…南宁市青秀区…」里切出 `南宁市`；找不到「市」返回 null */
function tokenFrom(x) {
  const i = x.indexOf('市')
  return i >= 1 ? x.slice(0, i + 1) : null
}

/** 去掉开头的省级前缀（剥完还剩不下东西就说明剥过头了，返回原串由调用方兜底） */
function stripProvince(s) {
  const full = s.replace(PROV_FULL, '')
  if (full !== s) return full
  const m = s.match(PROV_ABBR)
  if (m) {
    // 「广西区防城港市…」：简称后面还跟着个多余的「区」
    return s.slice(m[0].length).replace(/^(?:区|省)/, '')
  }
  return s
}

/**
 * 归一化单个地址。
 *
 * @param {string|null|undefined} raw 源表「地址」列原值
 * @param {Set<string>} [known] 本轮数据里**已知的城市名**（以「市」结尾），
 *        用于第 ② 条规则。可选 —— 不传就跳过该规则。
 *        ⚠️ 必须由**整批数据**先跑一遍 `toCity(x)` 再收集，
 *          否则「南宁片区」这种拿不到「市」的值无法反查出 `南宁市`。
 * @returns {string} 城市名；空输入返回 ''
 */
export function toCity(raw, known) {
  const s0 = String(raw ?? '').trim()
  if (!s0) return ''

  // 前缀噪声：「中国（广西）自由贸易试验区…」这类
  const s = s0.replace(/^中国（[^）]*）/, '').replace(/^自由贸易试验区/, '')

  // ① 剥省级前缀 → 取到第一个「市」
  const a = tokenFrom(stripProvince(s))
  if (a) return a

  // 剥过头了（「上海市」被剥成「市」）→ 拿没剥过的原串再试一次
  const b = tokenFrom(s)
  if (b) return b

  // ② 没有「市」→ 看串里有没有已知城市名（长的优先，「防城港市」先于「城港市」）
  if (known && known.size) {
    const names = [...known].filter((c) => c.endsWith('市')).sort((x, y) => y.length - x.length)
    for (const c of names) {
      if (s.includes(c.slice(0, -1))) return c
    }
  }

  // ③ 没有「市」但有「县」→ 取到第一个「县」（例：宁明县 / 兴安县）
  const j = s.indexOf('县')
  if (j >= 1) return s.slice(0, j + 1)

  // ④ 兜底：原样返回，宁可难看也不要静默丢掉信息
  return s0
}

/**
 * 整批归一化：先跑一遍收「已知城市名」，再正式归一化。
 * 顺序不能反 —— 第一遍能拿到全部以「市」结尾的城市，第二遍才用得上。
 *
 * @param {Array<string|null>} raws 原值数组
 * @returns {Array<string|null>} 与输入等长的城市数组（空 → null）
 */
export function toCityBatch(raws) {
  const known = new Set(raws.map((x) => toCity(x)).filter((c) => c.endsWith('市')))
  return raws.map((x) => toCity(x, known) || null)
}
